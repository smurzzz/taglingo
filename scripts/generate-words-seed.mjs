#!/usr/bin/env node
/**
 * Regenerates supabase/migrations/20260925000001_seed_words.sql and/or the
 * Phase 6 expansion migration 20260927000001_expand_vocabulary.sql from
 * docs/taglingo_words_template.csv so the seeds can never drift from the data.
 *
 * The seed file is FROZEN once applied; subsequent vocabulary growth must go
 * through --write-expansion, which emits only the delta (new CSV rows not yet
 * in the seed) and stays idempotent via a natural-key unique index + `on
 * conflict do nothing`.
 *
 *   node scripts/generate-words-seed.mjs                 # print seed to stdout
 *   node scripts/generate-words-seed.mjs --write         # rewrite the seed file
 *   node scripts/generate-words-seed.mjs --write-expansion  # write the delta migration
 *   node scripts/generate-words-seed.mjs --write-definitions  # write the definitions migration
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const csvPath = resolve(root, 'docs/taglingo_words_template.csv');
const migrationPath = resolve(root, 'supabase/migrations/20260925000001_seed_words.sql');
const expansionPath = resolve(root, 'supabase/migrations/20260927000001_expand_vocabulary.sql');
const definitionsPath = resolve(root, 'supabase/migrations/20260929000000_word_definitions.sql');

/** Minimal RFC-4180-ish parser: handles quoted fields and doubled quotes. */
function parseCsv(text) {
  const rows = [];
  let field = '';
  let row = [];
  let inQuotes = false;

  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (inQuotes) {
      if (ch === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i += 1;
        } else {
          inQuotes = false;
        }
      } else {
        field += ch;
      }
    } else if (ch === '"') {
      inQuotes = true;
    } else if (ch === ',') {
      row.push(field.trim());
      field = '';
    } else if (ch === '\n') {
      row.push(field.trim());
      field = '';
      rows.push(row);
      row = [];
    } else {
      field += ch;
    }
  }
  if (field !== '' || row.length) {
    row.push(field.trim());
    rows.push(row);
  }
  return rows.filter((r) => r.length > 1 && r.some((cell) => cell !== ''));
}

const sqlLiteral = (value) => `'${String(value ?? '').replace(/'/g, "''")}'`;
const sqlOrNull = (value) => (value ? sqlLiteral(value) : 'NULL');

function buildMigration(records) {
  const levels = ['Beginner', 'Intermediate', 'Advanced'];
  const byLevel = Object.fromEntries(levels.map((level) => [level, []]));
  for (const record of records) {
    const level = record.level ?? 'Beginner';
    if (!byLevel[level]) byLevel[level] = [];
    byLevel[level].push(record);
  }

  const valueRows = [];
  for (const level of levels) {
    const group = byLevel[level];
    if (group.length) valueRows.push(`  -- ${level.toLowerCase()} (${group.length})`);
    for (const r of group) {
      valueRows.push(
        `  (${sqlLiteral(r.tagalog)}, ${sqlLiteral(r.cebuano)}, ${sqlLiteral(r.english)}, '${level}', ${sqlOrNull(r.example_sentence)}, ${sqlOrNull(r.audio_url)}),`,
      );
    }
  }

  const total = records.length;
  return [
    '-- TagLingo — Phase 2: seed vocabulary from docs/taglingo_words_template.csv',
    `-- ${total} starter words: Beginner ${byLevel.Beginner.length} · Intermediate ${byLevel.Intermediate.length} · Advanced ${byLevel.Advanced.length}.`,
    '--',
    '-- GENERATED by scripts/generate-words-seed.mjs — do not edit by hand;',
    '-- edit the CSV and re-run `node scripts/generate-words-seed.mjs --write`.',
    '--',
    '-- Applies ONCE (Supabase CLI tracks applied migrations). Words are read-only',
    '-- for clients; this migration is the only write path until a service-role',
    '-- import expands the dataset toward the 200–300 target (Phase 6).',
    '',
    'insert into public.words (tagalog, cebuano, english, level, example_sentence, audio_url)',
    'values',
    ...valueRows.map((row, i) => (i === valueRows.length - 1 ? row.replace(/,$/, ';') : row)),
    '',
    '-- Post-seed sanity check (should read the counts above per level):',
    '--   select level, count(*) from public.words group by level order by level;',
    '',
  ].join('\n');
}

const isHeader = (cells) =>
  cells[0] === 'tagalog' && cells[1] === 'cebuano' && cells[2] === 'english' && cells[3] === 'level';

const records = parseCsv(readFileSync(csvPath, 'utf8'))
  .filter((cells) => !isHeader(cells))
  .map(([tagalog, cebuano, english, level, part_of_speech = '', definition = '', example_sentence = '', audio_url = '']) => ({
    tagalog,
    cebuano,
    english,
    level,
    part_of_speech,
    definition,
    example_sentence,
    audio_url,
  }));

/** Natural keys already committed via the frozen seed migration. */
function seededKeys(seedSql) {
  const keys = new Set();
  // value tuples look like  ('tagalog', 'cebuano', 'english', 'Level', ...),
  // always indented and paren-led, unlike comments/insert lines.
  const tupleRe = /^\s*\(\s*'((?:''|[^'])*)'\s*,\s*'((?:''|[^'])*)'/;
  for (const line of seedSql.split('\n')) {
    const m = tupleRe.exec(line);
    if (m) keys.add(`${m[1].replace(/''/g, "'")}\u0000${m[2].replace(/''/g, "'")}`);
  }
  return keys;
}

const naturalKey = (r) => `${r.tagalog}\u0000${r.cebuano}`;
const byLevelCounts = (list) => {
  const by = { Beginner: 0, Intermediate: 0, Advanced: 0 };
  for (const r of list) if (by[r.level] !== undefined) by[r.level] += 1;
  return by;
};

function buildExpansionMigration(delta) {
  const alreadySeeded = seededKeys(readFileSync(migrationPath, 'utf8'));
  const records = delta.filter((r) => !alreadySeeded.has(naturalKey(r)));
  const by = byLevelCounts(records);
  const total = records.length;

  const valueRows = records.map((r) =>
    `  (${sqlLiteral(r.tagalog)}, ${sqlLiteral(r.cebuano)}, ${sqlLiteral(r.english)}, '${r.level}', ${sqlOrNull(r.example_sentence)}, ${sqlOrNull(r.audio_url)}),`,
  );
  const leveled = [...'Beginner Intermediate Advanced'.split(' ')]
    .filter((level) => by[level] > 0)
    .map((level) => `${level} ${by[level]}`)
    .join(' · ');

  return [
    '-- TagLingo — Phase 6: vocabulary expansion from docs/taglingo_words_template.csv.',
    `-- Adds ${total} words not present in the frozen seed (${leveled}).`,
    '--',
    '-- GENERATED by scripts/generate-words-seed.mjs --write-expansion — do not edit',
    '-- by hand; edit the CSV and re-run the generator.',
    '--',
    '-- Idempotent: the natural-key index + `on conflict do nothing` makes this',
    '-- safe to reapply after future CSV additions (committed runs just no-op).',
    '',
    'create unique index if not exists words_tagalog_cebuano_english_key',
    '  on public.words (tagalog, cebuano, english);',
    '',
    'insert into public.words (tagalog, cebuano, english, level, example_sentence, audio_url)',
    'values',
    ...valueRows.map((row, i) => (i === valueRows.length - 1 ? row.replace(/,$/, '') : row)),
    'on conflict (tagalog, cebuano, english) do nothing;',
    '',
    '-- Sanity check (should show the dataset totals per level, incl. the seeds):',
    '--   select level, count(*) from public.words group by level order by level;',
    '',
  ].join('\n');
}

function buildDefinitionsMigration(records) {
  const tagged = records.filter((r) => r.part_of_speech);
  const defined = records.filter((r) => r.definition);
  const valueRows = records
    .filter((r) => r.part_of_speech || r.definition)
    .map(
      (r) =>
        `  (${sqlLiteral(r.tagalog)}, ${sqlLiteral(r.cebuano)}, ${sqlLiteral(r.english)}, ${sqlOrNull(r.part_of_speech)}, ${sqlOrNull(r.definition)}),`,
    );

  return [
    '-- TagLingo — curated part-of-speech + definition for every vocabulary row.',
    `-- Covers ${records.length} words (${tagged.length} tagged, ${defined.length} defined) from`,
    '-- docs/taglingo_words_template.csv. The DefinitionSheet shows these first and',
    '-- only falls back to the Free Dictionary API when a curated entry is missing.',
    '--',
    '-- GENERATED by scripts/generate-words-seed.mjs --write-definitions — do not edit',
    '-- by hand; edit the CSV and re-run the generator.',
    '--',
    '-- Idempotent: re-running after CSV edits updates the rows in place.',
    '',
    'alter table public.words add column if not exists part_of_speech text;',
    'alter table public.words add column if not exists definition     text;',
    '',
    'update public.words as w',
    'set part_of_speech = v.part_of_speech,',
    '    definition     = v.definition',
    'from (values',
    ...valueRows.map((row, i) =>
      i === valueRows.length - 1 ? `${row.replace(/,$/, '')}` : row,
    ),
    ') as v(tagalog, cebuano, english, part_of_speech, definition)',
    'where w.tagalog = v.tagalog',
    '  and w.cebuano = v.cebuano',
    '  and w.english = v.english',
    '  and (w.part_of_speech is distinct from v.part_of_speech',
    '    or w.definition is distinct from v.definition);',
    '',
    '-- Sanity checks:',
    '--   select count(*) from public.words where definition is not null;',
    '--   select level, count(*) from public.words group by level order by level;',
    '',
  ].join('\n');
}

if (process.argv.includes('--write-definitions')) {
  const sql = buildDefinitionsMigration(records);
  writeFileSync(definitionsPath, sql, 'utf8');
  console.log(`Wrote definitions migration -> ${definitionsPath}`);
  console.log(`  CSV rows: ${records.length} | tagged: ${records.filter((r) => r.part_of_speech).length} | defined: ${records.filter((r) => r.definition).length}`);
  console.log('  (apply + register in Supabase; the migration is idempotent)');
} else if (process.argv.includes('--write-expansion')) {
  const sql = buildExpansionMigration(records);
  writeFileSync(expansionPath, sql, 'utf8');
  const seeded = seededKeys(readFileSync(migrationPath, 'utf8')).size;
  const delta = records.length - seeded;
  console.log(`Wrote expansion migration -> ${expansionPath}`);
  console.log(
    `  CSV rows: ${records.length} | frozen seed keys: ${seeded} | delta rows: ${delta}`,
  );
  console.log('  (delta counts per level are in the file header; apply + register in Supabase)');
} else {
  const sql = buildMigration(records);
  if (process.argv.includes('--write')) {
    writeFileSync(migrationPath, sql, 'utf8');
    console.log(`Wrote ${records.length} rows -> ${migrationPath}`);
  } else {
    process.stdout.write(sql);
  }
}